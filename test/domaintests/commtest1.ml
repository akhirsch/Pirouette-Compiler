open Ppxlib
open Ast_builder.Default

let loc = Location.none

(* Tests the communication AST generated by eio_domains_backend.ml.

   How:
   Each assertion compares the generated expression against the expected
   call to the Pir_runtime module
   Command to Run Test: dune exec ./test/domaintests/commtest1.exe 

   Verifies:
   - The backend generates the correct runtime function calls for
     send, recv, choose, and recv_label
   - The generated calls contain the correct source, destination,
     values, and labels

   Note:
   Pir_runtime is a module defined within the runtime AST in
   eio_domains_backend.ml. It is included in generated OCaml programs,
   not the standalone pir_runtime.ml test file.

   Expected Terminal Output: 
    PASSED: send                       
    PASSED: recv
    PASSED: choose
    PASSED: recv_label  
    All communication generation tests passed.
*)

let check name actual expected =
  let actual_str = Format.asprintf "%a" Pprintast.expression actual in
  let expected_str = Format.asprintf "%a" Pprintast.expression expected in

  if actual_str <> expected_str then (
    Printf.eprintf "FAILED: %s\nExpected: %s\nActual: %s\n"
      name expected_str actual_str;
    failwith ("Test failed: " ^ name)
  );

  Printf.printf "PASSED: %s\n" name

(* Verify that send generates the correct destination and payload *)
let test_send () =
  let actual =
    Eio_domains_backend.send "Alice" (eint ~loc 42) "Bob"
  in
  let expected =
    [%expr Pir_runtime.send pir_chans ~me:"Alice" ~dest:"Bob" 42]
  in
  check "send" actual expected

(* Verify that recv generates the correct source and type annotation *)
let test_recv () =
  let actual =
    Eio_domains_backend.recv "Bob" [%type: int] "Alice"
  in
  let expected =
    [%expr (Pir_runtime.recv pir_chans ~me:"Bob" ~src:"Alice" : int)]
  in
  check "recv" actual expected

(* Verify that choose generates the correct label communication  *)
let test_choose () =
  let actual =
    Eio_domains_backend.choose "Alice" "Bob" "continue"
  in
  let expected =
    [%expr
      Pir_runtime.send_label pir_chans ~me:"Alice"
        ~dest:"Bob" "continue"]
  in
  check "choose" actual expected

(* Verify that recv_label generates the correct source location. *)
let test_recv_label () =
  let actual =
    Eio_domains_backend.recv_label "Bob" "Alice"
  in
  let expected =
    [%expr Pir_runtime.recv_label pir_chans ~me:"Bob" ~src:"Alice"]
  in
  check "recv_label" actual expected

(* Run all four communication generation tests *)
let () =
  test_send ();
  test_recv ();
  test_choose ();
  test_recv_label ();
  Printf.printf "All communication generation tests passed.\n"